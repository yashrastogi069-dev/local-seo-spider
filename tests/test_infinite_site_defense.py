def test_soft_404_content_deduplication(server, tmp_path_factory):
    """Verify soft-404 error pages returning 200 OK are deduplicated via content hash."""
    server.reset_counts()
    server.server.robots_status_code = 200
    server.server.robots_content = "User-agent: *\nAllow: /\n"

    engine = create_engine(tmp_path_factory, "serial")
    urls = [
        f"{server.base_url}/trap/soft-404/page1",
        f"{server.base_url}/trap/soft-404/page2",
        f"{server.base_url}/trap/soft-404/page3",
    ]
    req = CrawlRequest(
        start_url=urls[0],
        mode="list",
        url_list=urls,
        max_urls=10,
        delay_seconds=0.0,
        acknowledgment=True,
    )
    result = engine.run(req, lambda *_: None)

    # First page is indexed, subsequent identical pages are flagged as content duplicates
    assert len(result.pages) == 3
    duplicates = [p for p in result.pages if p.is_duplicate]
    assert len(duplicates) == 2
